//! Inbound SSG Directory Scanner & Deterministic `@embedFile` Manifest Generator (`src/ssg/manifest_gen.zig`).
//!
//! Converts any frontend static build output directory (Astro `dist/`, Next.js `out/`,
//! SvelteKit `build/`, Vite `dist/`) into a reproducible, sorted Zig source module backed by
//! `@embedFile("files/...")` and `zts_web.Assets`.
//!
//! Why files are staged alongside `assets_manifest.zig` inside `out_dir`:
//! - Zig `0.17.0` strictly forbids `@embedFile` from escaping outside a module's directory root.
//! - Staging normalized POSIX paths into `out_dir/files/...` guarantees 100% cross-platform success
//!   across Linux, macOS, and Windows (drive letters & backslashes never leak into generated code!).

const std = @import("std");
const Allocator = std.mem.Allocator;
const Io = std.Io;
const testing = std.testing;

/// What a manifest scan saw: how many files were embedded and how many bytes they add up to. Used
/// by `build.zig` to print the `files=… raw=… gzip=…` line CI asserts on.
pub const ManifestStats = struct {
    file_count: usize = 0,
    total_bytes: u64 = 0,
};

const ScannedEntry = struct {
    rel_posix: []u8, // e.g. `"index.html"`, `"docs/guide/index.html"`, `"_astro/app.js"`
    sha256_hex: [64]u8,
    size: u64,

    fn lessThan(_: void, a: ScannedEntry, b: ScannedEntry) bool {
        return std.mem.order(u8, a.rel_posix, b.rel_posix) == .lt;
    }
};

/// Recursively walks `src_dir`, copies every file cleanly into `out_dir/files/<rel_posix>`,
/// and emits a deterministic `out_dir/assets_manifest.zig` exposing:
/// - `pub const entries: []const web.StaticAsset`
/// - `pub const etags: []const [64]u8` (SHA-256 hex digests per entry)
/// - `pub const assets: web.Assets`
pub fn buildEmbeddedFrontendDir(
    allocator: Allocator,
    io: Io,
    src_dir: Io.Dir,
    out_dir: Io.Dir,
) !ManifestStats {
    var list: std.ArrayList(ScannedEntry) = .empty;
    defer {
        for (list.items) |it| allocator.free(it.rel_posix);
        list.deinit(allocator);
    }

    var total_bytes: u64 = 0;

    var walker = try src_dir.walk(allocator);
    defer walker.deinit();

    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;

        const norm = try allocator.dupe(u8, entry.path);
        errdefer allocator.free(norm);
        for (norm) |*ch| {
            if (ch.* == '\\') ch.* = '/';
        }

        const bytes = try src_dir.readFileAlloc(io, entry.path, allocator, .unlimited);
        defer allocator.free(bytes);

        var digest: [32]u8 = undefined;
        std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
        const hex = std.fmt.bytesToHex(digest, .lower);

        // Stage into `out_dir/files/<norm>`
        const staged_rel = try std.fmt.allocPrint(allocator, "files/{s}", .{norm});
        defer allocator.free(staged_rel);

        if (std.mem.lastIndexOfScalar(u8, staged_rel, '/')) |slash| {
            try out_dir.createDirPath(io, staged_rel[0..slash]);
        }
        try out_dir.writeFile(io, .{
            .sub_path = staged_rel,
            .data = bytes,
        });

        total_bytes += bytes.len;
        try list.append(allocator, .{
            .rel_posix = norm,
            .sha256_hex = hex,
            .size = bytes.len,
        });
    }

    // Sort lexicographically so output `assets_manifest.zig` is 100% deterministic across OS filesystems!
    std.mem.sort(ScannedEntry, list.items, {}, ScannedEntry.lessThan);

    var aw: std.Io.Writer.Allocating = .init(allocator);
    defer aw.deinit();
    const w = &aw.writer;

    try w.writeAll(
        \\// Auto-generated by Z-Ts `zts_ssg` (`embedFrontendDir`) — DO NOT EDIT MANUALLY.
        \\const web = @import("zts_web");
        \\
        \\pub const entries: []const web.StaticAsset = &.{
        \\
    );

    for (list.items) |item| {
        const route = try std.fmt.allocPrint(allocator, "/{s}", .{item.rel_posix});
        defer allocator.free(route);
        const embed_rel = try std.fmt.allocPrint(allocator, "files/{s}", .{item.rel_posix});
        defer allocator.free(embed_rel);

        try w.writeAll("    .{ .path = ");
        try writeZigStringLiteral(w, route);
        try w.writeAll(", .bytes = @embedFile(");
        try writeZigStringLiteral(w, embed_rel);
        try w.writeAll(") },\n");
    }

    try w.writeAll(
        \\};
        \\
        \\pub const sha256_digests: []const []const u8 = &.{
        \\
    );
    for (list.items) |item| {
        try w.writeAll("    \"");
        try w.writeAll(&item.sha256_hex);
        try w.writeAll("\",\n");
    }
    try w.writeAll(
        \\};
        \\
        \\pub const assets: web.Assets = .{
        \\    .entries = entries,
        \\};
        \\
    );

    try out_dir.writeFile(io, .{
        .sub_path = "assets_manifest.zig",
        .data = aw.written(),
    });

    return .{
        .file_count = list.items.len,
        .total_bytes = total_bytes,
    };
}

fn writeZigStringLiteral(writer: *std.Io.Writer, s: []const u8) std.Io.Writer.Error!void {
    try writer.writeByte('"');
    for (s) |c| {
        switch (c) {
            '\\' => try writer.writeAll("\\\\"),
            '"' => try writer.writeAll("\\\""),
            '\n' => try writer.writeAll("\\n"),
            '\r' => try writer.writeAll("\\r"),
            '\t' => try writer.writeAll("\\t"),
            else => {
                if (c < 0x20 or c >= 0x7f) {
                    var buf: [4]u8 = undefined;
                    const esc = std.fmt.bufPrint(&buf, "\\x{x:0>2}", .{c}) catch unreachable;
                    try writer.writeAll(esc);
                } else {
                    try writer.writeByte(c);
                }
            },
        }
    }
    try writer.writeByte('"');
}

test "buildEmbeddedFrontendDir deterministically sorts multi-page SSG trees and stages files" {
    var src_tmp = testing.tmpDir(.{});
    defer src_tmp.cleanup();
    var out_tmp = testing.tmpDir(.{});
    defer out_tmp.cleanup();

    try src_tmp.dir.createDirPath(testing.io, "_astro");
    try src_tmp.dir.createDirPath(testing.io, "docs/guide");
    try src_tmp.dir.writeFile(testing.io, .{ .sub_path = "docs/guide/index.html", .data = "<h1>Guide</h1>" });
    try src_tmp.dir.writeFile(testing.io, .{ .sub_path = "_astro/main.js", .data = "console.log(1);" });
    try src_tmp.dir.writeFile(testing.io, .{ .sub_path = "index.html", .data = "<h1>Home</h1>" });

    // `testing.tmpDir` opens non-iterable; reopen with `iterate = true` before walking.
    const src_dir = try src_tmp.dir.openDir(testing.io, ".", .{ .iterate = true });
    defer src_dir.close(testing.io);

    const stats = try buildEmbeddedFrontendDir(testing.allocator, testing.io, src_dir, out_tmp.dir);
    try testing.expectEqual(@as(usize, 3), stats.file_count);

    const manifest = try out_tmp.dir.readFileAlloc(testing.io, "assets_manifest.zig", testing.allocator, .unlimited);
    defer testing.allocator.free(manifest);

    // Must appear in strict lexicographical order regardless of creation/inode order:
    // 1. `/_astro/main.js`, 2. `/docs/guide/index.html`, 3. `/index.html`
    const p1 = std.mem.indexOf(u8, manifest, ".path = \"/_astro/main.js\"").?;
    const p2 = std.mem.indexOf(u8, manifest, ".path = \"/docs/guide/index.html\"").?;
    const p3 = std.mem.indexOf(u8, manifest, ".path = \"/index.html\"").?;
    try testing.expect(p1 < p2 and p2 < p3);
}
