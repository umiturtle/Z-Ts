fn commandTypePrefix(comptime cmd: anytype) []const u8 {
    comptime {
        if (cmd.prefix.len == 0) {
            return snakeToPascalComptime(cmd.fn_name);
        }
        return snakeToPascalComptime(cmd.ns_name) ++ snakeToPascalComptime(cmd.fn_name);
    }
}

fn emitCommandTypesComptime(comptime SchemaType: type) []const u8 {
    comptime {
        var out: []const u8 = "// Command Input / Output / ErrorSet Type Definitions\n";
        for (SchemaType.commands) |cmd| {
            const pfx = commandTypePrefix(cmd);
            if (cmd.Args != void) {
                out = out ++ "export type " ++ pfx ++ "Args = " ++ renderTsTypeComptime(cmd.Args, false) ++ ";\n";
            }
            out = out ++ "export type " ++ pfx ++ "Output = " ++ renderTsTypeComptime(cmd.Payload, true) ++ ";\n";
            const err_ts = if (cmd.ErrorSet) |ES| renderErrorSetTsType(@typeInfo(ES).error_set) else "never";
            out = out ++ "export type " ++ pfx ++ "Error = " ++ err_ts ++ ";\n\n";
        }
        return out;
    }
}

fn emitMethodSignatureParams(comptime cmd: anytype) []const u8 {
    comptime {
        const pfx = commandTypePrefix(cmd);
        if (cmd.Args == void) return "";
        if (cmd.args_optional) return "args?: " ++ pfx ++ "Args";
        return "args: " ++ pfx ++ "Args";
    }
}

fn emitTryMethodBodyComptime(comptime cmd: anytype, comptime indent: []const u8) []const u8 {
    comptime {
        const pfx = commandTypePrefix(cmd);
        const prop_key = formatTsPropertyKey(cmd.ts_method_name);
        const params = emitMethodSignatureParams(cmd);

        const wire_arg = if (cmd.Args == void)
            "{}"
        else if (cmd.args_optional)
            emitToWireExpr(cmd.Args, "(args ?? ({} as " ++ pfx ++ "Args))")
        else
            emitToWireExpr(cmd.Args, "args");

        const decoded_data = emitFromWireExpr(cmd.Payload, "_res.data", pfx ++ "Output");

        return indent ++ "async " ++ prop_key ++ "(" ++ params ++ "): Promise<RpcResult<" ++ pfx ++ "Output, " ++ pfx ++ "Error>> {\n" ++
            indent ++ "  const _res = await transport.invoke(\"" ++ cmd.wire_name ++ "\", " ++ wire_arg ++ ");\n" ++
            indent ++ "  if (!_res.ok) return _res as RpcErr<" ++ pfx ++ "Error>;\n" ++
            indent ++ "  return { ok: true, data: " ++ decoded_data ++ " };\n" ++
            indent ++ "},\n";
    }
}

fn emitThrowingMethodBodyComptime(comptime cmd: anytype, comptime try_target: []const u8, comptime indent: []const u8) []const u8 {
    comptime {
        const pfx = commandTypePrefix(cmd);
        const prop_key = formatTsPropertyKey(cmd.ts_method_name);
        const params = emitMethodSignatureParams(cmd);
        const forward = if (cmd.Args == void) "()" else "(args)";

        return indent ++ "async " ++ prop_key ++ "(" ++ params ++ "): Promise<" ++ pfx ++ "Output> {\n" ++
            indent ++ "  const _r = await " ++ try_target ++ forward ++ ";\n" ++
            indent ++ "  if (!_r.ok) throw new ZtsRpcError<" ++ pfx ++ "Error>(_r.error.code);\n" ++
            indent ++ "  return _r.data;\n" ++
            indent ++ "},\n";
    }
}

fn emitClientFactoryComptime(comptime SchemaType: type) []const u8 {
    comptime {
        var try_root: []const u8 = "";
        var throw_root: []const u8 = "";

        // 1. Root-level commands (`prefix == ""`)
        for (SchemaType.commands) |cmd| {
            if (cmd.prefix.len != 0) continue;
            try_root = try_root ++ emitTryMethodBodyComptime(cmd, "    ");
            const access = if (naming.needsPropertyQuotes(cmd.ts_method_name))
                "_try[\"" ++ cmd.ts_method_name ++ "\"]"
            else
                "_try." ++ cmd.ts_method_name;
            throw_root = throw_root ++ emitThrowingMethodBodyComptime(cmd, access, "    ");
        }

        // 2. Prefixed plugin namespaces (`prefix != ""`) grouped cleanly under `client.<ns>.<cmd>`
        for (SchemaType.namespaces, 0..) |ns, ns_idx| {
            if (ns.prefix.len == 0) continue;
            var has_any = false;
            var ns_try_methods: []const u8 = "";
            var ns_throw_methods: []const u8 = "";
            const ns_key = formatTsPropertyKey(ns.name);
            const ns_access = if (naming.needsPropertyQuotes(ns.name))
                "_try[\"" ++ ns.name ++ "\"]"
            else
                "_try." ++ ns.name;

            for (SchemaType.commands) |cmd| {
                if (cmd.ns_index != ns_idx) continue;
                has_any = true;
                ns_try_methods = ns_try_methods ++ emitTryMethodBodyComptime(cmd, "      ");
                const m_access = if (naming.needsPropertyQuotes(cmd.ts_method_name))
                    ns_access ++ "[\"" ++ cmd.ts_method_name ++ "\"]"
                else
                    ns_access ++ "." ++ cmd.ts_method_name;
                ns_throw_methods = ns_throw_methods ++ emitThrowingMethodBodyComptime(cmd, m_access, "      ");
            }

            if (has_any) {
                try_root = try_root ++ "    " ++ ns_key ++ ": {\n" ++ ns_try_methods ++ "    },\n";
                throw_root = throw_root ++ "    " ++ ns_key ++ ": {\n" ++ ns_throw_methods ++ "    },\n";
            }
        }

        return "// Type-Safe RPC Client Factory\n" ++
            "export function createRpcClient(transport: RpcTransport = createIpcTransport()) {\n" ++
            "  const _try = {\n" ++
            try_root ++
            "  };\n" ++
            "  return {\n" ++
            "    $try: _try,\n" ++
            throw_root ++
            "  };\n" ++
            "}\n\n" ++
            "export type RpcClient = ReturnType<typeof createRpcClient>;\n";
    }
}

