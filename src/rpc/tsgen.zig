fn snakeToPascalComptime(comptime s: []const u8) []const u8 {
    comptime {
        var out: []const u8 = "";
        var cap_next = true;
        for (s) |c| {
            if (c == '_' or c == '-' or c == ':' or c == '|') {
                cap_next = true;
                continue;
            }
            if (cap_next) {
                out = out ++ &[_]u8{std.ascii.toUpper(c)};
                cap_next = false;
            } else {
                out = out ++ &[_]u8{c};
            }
        }
        return if (out.len == 0) "Anon" else out;
    }
}

fn handleTypeAliasName(comptime H: type) []const u8 {
    return comptime snakeToPascalComptime(types.handleTagName(H)) ++ "Handle";
}

fn formatTsPropertyKey(comptime prop: []const u8) []const u8 {
    if (comptime naming.needsPropertyQuotes(prop)) {
        return "\"" ++ prop ++ "\"";
    }
    return prop;
}

fn collectHandleTagsFromType(comptime T: type, comptime existing: []const []const u8) []const []const u8 {
    comptime {
        if (types.isHandleType(T)) {
            const tag = types.handleTagName(T);
            for (existing) |e| {
                if (std.mem.eql(u8, e, tag)) return existing;
            }
            return existing ++ &[_][]const u8{tag};
        }

        switch (@typeInfo(T)) {
            .optional => |opt| return collectHandleTagsFromType(opt.child, existing),
            .array => |arr| return collectHandleTagsFromType(arr.child, existing),
            .vector => |vec| return collectHandleTagsFromType(vec.child, existing),
            .pointer => |ptr| switch (ptr.size) {
                .one, .slice => return collectHandleTagsFromType(ptr.child, existing),
                else => return existing,
            },
            .@"struct" => |s| {
                if (types.isBigIntType(T) or T == types.SafeInt or T == types.Bytes or T == types.OsPath or T == core.OwnedBytes) {
                    return existing;
                }
                if (types.isTaggedUnionWrapper(T)) {
                    return collectHandleTagsFromType(T.InnerUnion, existing);
                }
                var acc = existing;
                for (s.field_types) |FT| {
                    acc = collectHandleTagsFromType(FT, acc);
                }
                return acc;
            },
            .@"union" => |u| {
                if (types.isPatchType(T)) {
                    return collectHandleTagsFromType(T.Child, existing);
                }
                var acc = existing;
                for (u.field_types) |FT| {
                    acc = collectHandleTagsFromType(FT, acc);
                }
                return acc;
            },
            else => return existing,
        }
    }
}

fn emitHandleBrandsComptime(comptime SchemaType: type) []const u8 {
    comptime {
        var tags: []const []const u8 = &.{};
        for (SchemaType.commands) |cmd| {
            tags = collectHandleTagsFromType(cmd.Args, tags);
            tags = collectHandleTagsFromType(cmd.Payload, tags);
        }
        if (tags.len == 0) return "";

        var out: []const u8 = "// Nominal 53-bit Generational Resource Handles\n";
        for (tags) |tag| {
            const alias_name = snakeToPascalComptime(tag) ++ "Handle";
            out = out ++ "export type " ++ alias_name ++ " = Brand<number, \"" ++ tag ++ "\">;\n";
        }
        return out ++ "\n";
    }
}

/// Renders a Zig type `T` into its exact TypeScript type expression at `comptime`.
pub fn renderTsTypeComptime(comptime T: type, comptime is_return_pos: bool) []const u8 {
    comptime {
        if (T == core.OwnedBytes or T == types.Bytes) return "Uint8Array";
        if (T == types.OsPath) return "OsPathValue";
        if (T == types.SafeInt) return "number";
        if (types.isBigIntType(T)) return "bigint";
        if (types.isHandleType(T)) return handleTypeAliasName(T);
        if (types.isTaggedUnionWrapper(T)) return renderUnionTsType(T.InnerUnion, T.union_config);

        return switch (@typeInfo(T)) {
            .void => if (is_return_pos) "void" else "null",
            .null => "null",
            .bool => "boolean",
            .int, .comptime_int, .float, .comptime_float => "number",
            .optional => |opt| renderTsTypeComptime(opt.child, false) ++ " | null",
            .@"enum" => |e| blk: {
                if (e.field_names.len == 0) break :blk "never";
                var acc: []const u8 = "";
                for (e.field_names, 0..) |fname, i| {
                    if (i > 0) acc = acc ++ " | ";
                    acc = acc ++ "\"" ++ fname ++ "\"";
                }
                break :blk acc;
            },
            .error_set => |es| renderErrorSetTsType(es),
            .array => |arr| "readonly (" ++ renderTsTypeComptime(arr.child, false) ++ ")[]",
            .vector => |vec| "readonly (" ++ renderTsTypeComptime(vec.child, false) ++ ")[]",
            .pointer => |ptr| switch (ptr.size) {
                .one => switch (@typeInfo(ptr.child)) {
                    .array => |arr| if (arr.child == u8) "string" else "readonly (" ++ renderTsTypeComptime(arr.child, false) ++ ")[]",
                    else => renderTsTypeComptime(ptr.child, false),
                },
                .slice => if (ptr.child == u8) "string" else "readonly (" ++ renderTsTypeComptime(ptr.child, false) ++ ")[]",
                else => "unknown",
            },
            .@"struct" => |s| blk: {
                if (@hasDecl(T, "zts_ts_type")) break :blk T.zts_ts_type;
                if (std.meta.hasFn(T, "jsonStringify") or std.meta.hasFn(T, "jsonParse") or std.meta.hasFn(T, "decodeZtsJson")) {
                    break :blk "unknown";
                }
                if (s.is_tuple) {
                    var tup: []const u8 = "readonly [";
                    for (s.field_types, 0..) |FT, i| {
                        if (i > 0) tup = tup ++ ", ";
                        tup = tup ++ renderTsTypeComptime(FT, false);
                    }
                    break :blk tup ++ "]";
                }
                break :blk "{ " ++ renderStructFieldsTsComptime(T, null) ++ "}";
            },
            .@"union" => blk: {
                if (types.isPatchType(T)) {
                    break :blk renderTsTypeComptime(T.Child, false) ++ " | null";
                }
                if (std.meta.hasFn(T, "jsonStringify") or std.meta.hasFn(T, "jsonParse")) {
                    break :blk "unknown";
                }
                break :blk renderUnionTsType(T, types.resolveUnionConfig(T, .internal));
            },
            else => "unknown",
        };
    }
}

fn renderStructFieldsTsComptime(comptime S: type, comptime prefix_entry: ?[]const u8) []const u8 {
    comptime {
        const s = @typeInfo(S).@"struct";
        var acc: []const u8 = if (prefix_entry) |p| (p ++ "; ") else "";
        for (s.field_names, s.field_types, s.field_attrs) |fname, FType, fattr| {
            if (FType == void) continue;
            const wire_name = naming.snakeToCamel(fname);
            const prop_key = formatTsPropertyKey(wire_name);

            if (types.isPatchType(FType)) {
                acc = acc ++ "readonly " ++ prop_key ++ "?: " ++ renderTsTypeComptime(FType.Child, false) ++ " | null; ";
            } else if (@typeInfo(FType) == .optional) {
                const inner = renderTsTypeComptime(@typeInfo(FType).optional.child, false) ++ " | null";
                if (fattr.defaultValue(FType) != null) {
                    acc = acc ++ "readonly " ++ prop_key ++ "?: " ++ inner ++ "; ";
                } else {
                    acc = acc ++ "readonly " ++ prop_key ++ ": " ++ inner ++ "; ";
                }
            } else {
                const inner = renderTsTypeComptime(FType, false);
                if (fattr.defaultValue(FType) != null) {
                    acc = acc ++ "readonly " ++ prop_key ++ "?: " ++ inner ++ "; ";
                } else {
                    acc = acc ++ "readonly " ++ prop_key ++ ": " ++ inner ++ "; ";
                }
            }
        }
        return acc;
    }
}

fn renderUnionTsType(comptime U: type, comptime cfg: types.UnionConfig) []const u8 {
    comptime {
        const u = @typeInfo(U).@"union";
        if (u.field_names.len == 0) return "never";
        var acc: []const u8 = "";

        for (u.field_names, u.field_types, 0..) |v_name, PayloadType, i| {
            if (i > 0) acc = acc ++ " | ";
            const tag_prop = formatTsPropertyKey(cfg.tag_field);
            const content_prop = formatTsPropertyKey(cfg.content_field);

            switch (cfg.style) {
                .internal => {
                    const tag_entry = "readonly " ++ tag_prop ++ ": \"" ++ v_name ++ "\"";
                    if (PayloadType == void) {
                        acc = acc ++ "{ " ++ tag_entry ++ " }";
                    } else if (@typeInfo(PayloadType) == .@"struct" and !@typeInfo(PayloadType).@"struct".is_tuple and
                        !types.isBigIntType(PayloadType) and PayloadType != types.SafeInt and
                        PayloadType != types.Bytes and PayloadType != types.OsPath and
                        !types.isHandleType(PayloadType) and !types.isTaggedUnionWrapper(PayloadType) and
                        !(std.meta.hasFn(PayloadType, "jsonStringify") or std.meta.hasFn(PayloadType, "jsonParse")))
                    {
                        acc = acc ++ "{ " ++ renderStructFieldsTsComptime(PayloadType, tag_entry) ++ "}";
                    } else {
                        acc = acc ++ "{ " ++ tag_entry ++ "; readonly " ++ content_prop ++ ": " ++ renderTsTypeComptime(PayloadType, false) ++ " }";
                    }
                },
                .adjacent => {
                    const tag_entry = "readonly " ++ tag_prop ++ ": \"" ++ v_name ++ "\"";
                    if (PayloadType == void) {
                        acc = acc ++ "{ " ++ tag_entry ++ " }";
                    } else {
                        acc = acc ++ "{ " ++ tag_entry ++ "; readonly " ++ content_prop ++ ": " ++ renderTsTypeComptime(PayloadType, false) ++ " }";
                    }
                },
                .external => {
                    if (PayloadType == void) {
                        acc = acc ++ "\"" ++ v_name ++ "\"";
                    } else {
                        const v_key = formatTsPropertyKey(v_name);
                        acc = acc ++ "{ readonly " ++ v_key ++ ": " ++ renderTsTypeComptime(PayloadType, false) ++ " }";
                    }
                },
                .untagged => {
                    acc = acc ++ "(" ++ renderTsTypeComptime(PayloadType, false) ++ ")";
                },
            }
        }
        return acc;
    }
}

fn renderErrorSetTsType(comptime es_info: std.builtin.Type.ErrorSet) []const u8 {
    comptime {
        const names = es_info.error_names orelse return "string";
        if (names.len == 0) return "never";
        // Sort deterministically so generated `.ts` output NEVER depends on Zig's global
        // translation-unit error-table registration order!
        var sorted: [names.len][:0]const u8 = names[0..names.len].*;
        var i: usize = 1;
        while (i < sorted.len) : (i += 1) {
            const cur = sorted[i];
            var j: usize = i;
            while (j > 0 and std.mem.order(u8, sorted[j - 1], cur) == .gt) : (j -= 1) {
                sorted[j] = sorted[j - 1];
            }
            sorted[j] = cur;
        }
        var acc: []const u8 = "";
        for (sorted, 0..) |err_name, idx| {
            if (idx > 0) acc = acc ++ " | ";
            acc = acc ++ "\"" ++ err_name ++ "\"";
        }
        return acc;
    }
}

// ============================================================================
// Automatic Zero-Overhead Wire Transcoding (BigInt <-> string, Uint8Array <-> Base64)
// ============================================================================

fn needsWireTranscode(comptime T: type) bool {
    comptime {
        if (types.isBigIntType(T) or T == types.Bytes or T == core.OwnedBytes) return true;
        if (T == types.SafeInt or T == types.OsPath or types.isHandleType(T)) return false;
        if (types.isTaggedUnionWrapper(T)) return needsWireTranscode(T.InnerUnion);

        return switch (@typeInfo(T)) {
            .optional => |opt| needsWireTranscode(opt.child),
            .array => |arr| needsWireTranscode(arr.child),
            .vector => |vec| needsWireTranscode(vec.child),
            .pointer => |ptr| switch (ptr.size) {
                .one, .slice => if (ptr.child == u8) false else needsWireTranscode(ptr.child),
                else => false,
            },
            .@"struct" => |s| blk: {
                if (std.meta.hasFn(T, "jsonStringify") or std.meta.hasFn(T, "jsonParse")) break :blk false;
                for (s.field_types) |FT| {
                    if (needsWireTranscode(FT)) break :blk true;
                }
                break :blk false;
            },
            .@"union" => |u| blk: {
                if (types.isPatchType(T)) break :blk needsWireTranscode(T.Child);
                if (std.meta.hasFn(T, "jsonStringify") or std.meta.hasFn(T, "jsonParse")) break :blk false;
                for (u.field_types) |FT| {
                    if (needsWireTranscode(FT)) break :blk true;
                }
                break :blk false;
            },
            else => false,
        };
    }
}

/// Generates a TypeScript expression converting TS value `expr` -> JSON wire representation.
fn emitToWireExpr(comptime T: type, comptime expr: []const u8) []const u8 {
    comptime {
        if (!needsWireTranscode(T)) return expr;
        if (types.isBigIntType(T)) return "(" ++ expr ++ ").toString()";
        if (T == types.Bytes or T == core.OwnedBytes) return "_bytesToBase64(" ++ expr ++ ")";
        if (types.isTaggedUnionWrapper(T)) return emitUnionTranscodeExpr(T.InnerUnion, T.union_config, expr, true);

        return switch (@typeInfo(T)) {
            .optional => |opt| "(" ++ expr ++ " === null || " ++ expr ++ " === undefined ? " ++ expr ++ " : " ++ emitToWireExpr(opt.child, expr) ++ ")",
            .array => |arr| "(" ++ expr ++ ").map((_e) => " ++ emitToWireExpr(arr.child, "_e") ++ ")",
            .vector => |vec| "(" ++ expr ++ ").map((_e) => " ++ emitToWireExpr(vec.child, "_e") ++ ")",
            .pointer => |ptr| switch (ptr.size) {
                .one => emitToWireExpr(ptr.child, expr),
                .slice => "(" ++ expr ++ ").map((_e) => " ++ emitToWireExpr(ptr.child, "_e") ++ ")",
                else => expr,
            },
            .@"struct" => |s| blk: {
                if (s.is_tuple) {
                    var tup: []const u8 = "[";
                    for (s.field_types, 0..) |FT, i| {
                        if (i > 0) tup = tup ++ ", ";
                        tup = tup ++ emitToWireExpr(FT, std.fmt.comptimePrint("{s}[{d}]", .{ expr, i }));
                    }
                    break :blk tup ++ "]";
                }
                break :blk emitStructTranscodeExpr(T, expr, true);
            },
            .@"union" => if (types.isPatchType(T))
                "(" ++ expr ++ " === null || " ++ expr ++ " === undefined ? " ++ expr ++ " : " ++ emitToWireExpr(T.Child, expr) ++ ")"
            else
                emitUnionTranscodeExpr(T, types.resolveUnionConfig(T, .internal), expr, true),
            else => expr,
        };
    }
}

/// Generates a TypeScript expression converting JSON wire representation `expr` -> rich TS value.
fn emitFromWireExpr(comptime T: type, comptime expr: []const u8, comptime ts_target: []const u8) []const u8 {
    comptime {
        if (T == void) return "undefined";
        if (!needsWireTranscode(T)) return "(" ++ expr ++ " as " ++ ts_target ++ ")";
        if (types.isBigIntType(T)) return "BigInt(" ++ expr ++ " as string)";
        if (T == types.Bytes or T == core.OwnedBytes) return "_base64ToBytes(" ++ expr ++ ")";
        if (types.isTaggedUnionWrapper(T)) return emitUnionTranscodeExpr(T.InnerUnion, T.union_config, expr, false);

        return switch (@typeInfo(T)) {
            .optional => |opt| "(" ++ expr ++ " === null || " ++ expr ++ " === undefined ? null : " ++ emitFromWireExpr(opt.child, expr, renderTsTypeComptime(opt.child, false)) ++ ")",
            .array => |arr| "(" ++ expr ++ " as unknown[]).map((_e) => " ++ emitFromWireExpr(arr.child, "_e", renderTsTypeComptime(arr.child, false)) ++ ")",
            .vector => |vec| "(" ++ expr ++ " as unknown[]).map((_e) => " ++ emitFromWireExpr(vec.child, "_e", renderTsTypeComptime(vec.child, false)) ++ ")",
            .pointer => |ptr| switch (ptr.size) {
                .one => emitFromWireExpr(ptr.child, expr, renderTsTypeComptime(ptr.child, false)),
                .slice => "(" ++ expr ++ " as unknown[]).map((_e) => " ++ emitFromWireExpr(ptr.child, "_e", renderTsTypeComptime(ptr.child, false)) ++ ")",
                else => "(" ++ expr ++ " as " ++ ts_target ++ ")",
            },
            .@"struct" => |s| blk: {
                if (s.is_tuple) {
                    var tup: []const u8 = "[";
                    for (s.field_types, 0..) |FT, i| {
                        if (i > 0) tup = tup ++ ", ";
                        const item_expr = std.fmt.comptimePrint("({s} as unknown[])[{d}]", .{ expr, i });
                        tup = tup ++ emitFromWireExpr(FT, item_expr, renderTsTypeComptime(FT, false));
                    }
                    break :blk tup ++ "] as const";
                }
                break :blk emitStructTranscodeExpr(T, expr, false);
            },
            .@"union" => if (types.isPatchType(T))
                "(" ++ expr ++ " === null || " ++ expr ++ " === undefined ? " ++ expr ++ " : " ++ emitFromWireExpr(T.Child, expr, renderTsTypeComptime(T.Child, false)) ++ ")"
            else
                emitUnionTranscodeExpr(T, types.resolveUnionConfig(T, .internal), expr, false),
            else => "(" ++ expr ++ " as " ++ ts_target ++ ")",
        };
    }
}

fn emitStructTranscodeExpr(comptime S: type, comptime expr: []const u8, comptime to_wire: bool) []const u8 {
    comptime {
        const s = @typeInfo(S).@"struct";
        var body: []const u8 = "(() => { const _o: Record<string, unknown> = { ...(" ++ expr ++ " as Record<string, unknown>) }; ";
        for (s.field_names, s.field_types) |fname, FT| {
            if (!needsWireTranscode(FT)) continue;
            const key = naming.snakeToCamel(fname);
            const access = "_o[\"" ++ key ++ "\"]";
            const converted = if (to_wire)
                emitToWireExpr(FT, access ++ " as " ++ renderTsTypeComptime(FT, false))
            else
                emitFromWireExpr(FT, access, renderTsTypeComptime(FT, false));
            body = body ++ "if (\"" ++ key ++ "\" in _o && " ++ access ++ " !== undefined) _o[\"" ++ key ++ "\"] = " ++ converted ++ "; ";
        }
        return body ++ "return _o as unknown as " ++ (if (to_wire) "Record<string, unknown>" else renderTsTypeComptime(S, false)) ++ "; })()";
    }
}

fn emitUnionTranscodeExpr(comptime U: type, comptime cfg: types.UnionConfig, comptime expr: []const u8, comptime to_wire: bool) []const u8 {
    comptime {
        if (cfg.style != .internal and cfg.style != .adjacent) {
            return "(" ++ expr ++ " as unknown as " ++ (if (to_wire) "unknown" else renderTsTypeComptime(U, false)) ++ ")";
        }
        const u = @typeInfo(U).@"union";
        var body: []const u8 = "(() => { const _u = " ++ expr ++ " as Record<string, unknown>; switch (_u[\"" ++ cfg.tag_field ++ "\"]) { ";
        for (u.field_names, u.field_types) |v_name, PT| {
            if (!needsWireTranscode(PT)) continue;
            body = body ++ "case \"" ++ v_name ++ "\": ";
            if (cfg.style == .adjacent or @typeInfo(PT) != .@"struct") {
                const inner = if (to_wire)
                    emitToWireExpr(PT, "_u[\"" ++ cfg.content_field ++ "\"] as " ++ renderTsTypeComptime(PT, false))
                else
                    emitFromWireExpr(PT, "_u[\"" ++ cfg.content_field ++ "\"]", renderTsTypeComptime(PT, false));
                body = body ++ "return { ..._u, [\"" ++ cfg.content_field ++ "\"]: " ++ inner ++ " }; ";
            } else {
                const inner = emitStructTranscodeExpr(PT, "_u", to_wire);
                body = body ++ "return " ++ inner ++ "; ";
            }
        }
        body = body ++ "default: return _u; } })() as unknown as " ++ (if (to_wire) "unknown" else renderTsTypeComptime(U, false));
        return body;
    }
}

