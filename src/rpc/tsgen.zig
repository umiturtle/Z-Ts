//! `comptime` TypeScript Client & Strict Type Generator (`src/rpc/tsgen.zig`).
//!
//! Generates complete, self-contained, zero-dependency TypeScript bindings directly from any
//! `zts_rpc.Schema(...)` definition at `comptime` (`Schema.ts_bindings`) or runtime (`writeBindings`).
//!
//! Strict TypeScript guarantees verified automatically against real `tsc`:
//! - `--strict` (`noImplicitAny`, `strictNullChecks`, `useUnknownInCatchVariables`, etc.)
//! - `--exactOptionalPropertyTypes` (`T | null` vs `prop?: T` vs `prop?: T | null` via `Patch(T)`)
//! - `--erasableSyntaxOnly` (zero TS `enum`, zero `namespace`, zero parameter properties; runs natively on Node 22+)
//! - Full JS/TS reserved keyword escaping (`delete`, `class`, `default`, etc.) & hyphenated property quoting (`"aria-label"`)
//! - Nominal `Brand<number, Tag>` handles (`WindowHandle` != `FileHandle` at compile time!)
//! - Exhaustive `ErrorSet` union types (`client.$try.<cmd>(...)` -> `Promise<RpcResult<T, CmdError>>`)
//! - Automatic zero-overhead `bigint` ⇔ decimal string and `Uint8Array` ⇔ Base64 wire transcoding.

const std = @import("std");
const builtin = @import("builtin");
const Allocator = std.mem.Allocator;
const testing = std.testing;

const core = @import("zts_foundation");
const naming = @import("naming.zig");
const types = @import("types.zig");

/// Generates the full `.ts` module at `comptime` as a static string slice (`Schema.ts_bindings`).
pub fn generateComptime(comptime SchemaType: type) []const u8 {
    comptime {
        @setEvalBranchQuota(500_000);
        var buf: []const u8 = "";
        buf = buf ++ preamble_ts;
        buf = buf ++ emitHandleBrandsComptime(SchemaType);
        buf = buf ++ emitCommandTypesComptime(SchemaType);
        buf = buf ++ emitClientFactoryComptime(SchemaType);
        return buf;
    }
}

/// Allocates and emits the full `.ts` module at runtime.
pub fn generateAlloc(allocator: Allocator, comptime SchemaType: type) Allocator.Error![]u8 {
    return allocator.dupe(u8, SchemaType.ts_bindings);
}

