fn ensureTscJsPathAlloc(allocator: Allocator, io: std.Io) ![]u8 {
    const cache_dir_rel = ".zig-cache/zts-ts-toolchain";
    const tsc_rel = cache_dir_rel ++ "/node_modules/typescript/lib/tsc.js";

    const cwd = std.Io.Dir.cwd();
    if (cwd.access(io, tsc_rel, .{})) |_| {
        return allocator.dupe(u8, tsc_rel);
    } else |_| {}

    try cwd.createDirPath(io, cache_dir_rel);

    const npm_argv: []const []const u8 = if (builtin.os.tag == .windows)
        &.{ "cmd.exe", "/c", "npm", "install", "--prefix", cache_dir_rel, "--no-save", "--no-audit", "--no-fund", "typescript@7.0.2" }
    else
        &.{ "npm", "install", "--prefix", cache_dir_rel, "--no-save", "--no-audit", "--no-fund", "typescript@7.0.2" };

    const res = try std.process.run(allocator, io, .{ .argv = npm_argv });
    defer allocator.free(res.stdout);
    defer allocator.free(res.stderr);

    if (!res.term.success()) {
        std.debug.print("npm install typescript failed:\nstdout: {s}\nstderr: {s}\n", .{ res.stdout, res.stderr });
        return error.TscBootstrapFailed;
    }
    return allocator.dupe(u8, tsc_rel);
}

test "tsgen passes real `tsc --noEmit --strict --exactOptionalPropertyTypes --erasableSyntaxOnly` & executes live Node <-> Zig RPC roundtrip" {
    const schema_mod = @import("schema.zig");
    const FileHandle = types.Handle(.file);

    const DrawShape = union(enum) {
        circle: struct { radius: f64 },
        label: []const u8,
        clear: void,
    };

    const AdjacentEvent = types.TaggedUnion(union(enum) {
        resized: struct { w: u32, h: u32 },
        closed: void,
    }, .{ .style = .adjacent, .tag_field = "t", .content_field = "c" });

    const ExternalFilter = types.TaggedUnion(union(enum) {
        by_ext: []const u8,
        any: void,
    }, .{ .style = .external });

    const UntaggedScalar = types.TaggedUnion(union(enum) {
        text: []const u8,
        flag: bool,
    }, .{ .style = .untagged });

    const AppState = struct {
        balance: i128 = 9007199254740995,
        theme: enum { light, dark } = .dark,
        bio: ?[]const u8 = "initial",
    };

    const CoreCmds = struct {
        // 1. BigInt + Uint8Array + hyphenated CSS/ARIA keys + optional defaults
        pub fn transfer_ledger(state: *AppState, args: struct {
            delta: types.BigInt(i128),
            signature: types.Bytes,
            @"aria-label": []const u8,
            note: ?[]const u8 = null,
            retry_limit: u16 = 3,
        }) error{ InsufficientFunds, InvalidSignature }!struct {
            new_balance: types.BigInt(i128),
            echo_sig: types.Bytes,
            label_len: u32,
        } {
            if (args.signature.len() == 0) return error.InvalidSignature;
            const next = state.balance + args.delta.get();
            if (next < 0) return error.InsufficientFunds;
            state.balance = next;
            return .{
                .new_balance = .init(state.balance),
                .echo_sig = args.signature,
                .label_len = @intCast(args.@"aria-label".len),
            };
        }

        // 2. 3-state `Patch(T)` + All 4 `union(enum)` styles + CSS `--var` + `OsPath` + required nullable field
        pub fn update_profile(state: *AppState, args: struct {
            req_token: ?[]const u8,
            bio: types.Patch([]const u8) = .unchanged,
            shape: DrawShape,
            adj_event: ?AdjacentEvent = null,
            ext_filter: ?ExternalFilter = null,
            scalar: ?UntaggedScalar = null,
            @"--accent-color": []const u8 = "#00ffaa",
            avatar_path: ?types.OsPath = null,
        }) []const u8 {
            args.bio.apply(&state.bio);
            _ = args.req_token;
            _ = args.adj_event;
            _ = args.ext_filter;
            _ = args.scalar;
            _ = args.@"--accent-color";
            _ = args.avatar_path;
            return switch (args.shape) {
                .circle => "circle",
                .label => |s| s,
                .clear => state.bio orelse "cleared-bio",
            };
        }

        // 3. Nominal Branded Handles (`Handle(.window)` vs `Handle(.file)`)
        pub fn inspect_handle(args: struct {
            win: types.Handle(.window),
            file: FileHandle,
        }) types.Handle(.window) {
            _ = args.file;
            return args.win;
        }

        // 4. JS reserved word `delete` command with omittable all-default args
        pub fn delete(args: struct { force: bool = false }) bool {
            return args.force;
        }
    };

    const WindowPlugin = struct {
        pub const rpc_prefix = "plugin:window|";

        pub fn set_title(args: struct {
            window: types.Handle(.window),
            title: []const u8,
        }) error{WindowNotFound}!void {
            if (args.title.len == 0) return error.WindowNotFound;
        }
    };

    const ShowcaseRpc = schema_mod.Schema(.{
        .app = .{ .prefix = "", .State = AppState, .Cmds = CoreCmds },
        .window = WindowPlugin,
    });

    // Write generated `bindings.gen.ts` + copy `tests/tsgen/verify_client.ts` into an isolated temp directory
    var tmp = testing.tmpDir(.{});
    defer tmp.cleanup();

    try tmp.dir.writeFile(testing.io, .{
        .sub_path = "bindings.gen.ts",
        .data = ShowcaseRpc.ts_bindings,
    });

    const verify_src = try std.Io.Dir.cwd().readFileAlloc(
        testing.io,
        "tests/tsgen/verify_client.ts",
        testing.allocator,
        .unlimited,
    );
    defer testing.allocator.free(verify_src);

    try tmp.dir.writeFile(testing.io, .{
        .sub_path = "package.json",
        .data = "{\"type\":\"module\"}\n",
    });

    try tmp.dir.writeFile(testing.io, .{
        .sub_path = "verify_client.ts",
        .data = verify_src,
    });

    // Resolve real path to `tsc.js` (auto-bootstrapping TypeScript into `.zig-cache/zts-ts-toolchain` on cold runs)
    const tsc_js_rel = try ensureTscJsPathAlloc(testing.allocator, testing.io);
    defer testing.allocator.free(tsc_js_rel);

    const cwd_abs = try std.process.currentPathAlloc(testing.io, testing.allocator);
    defer testing.allocator.free(cwd_abs);
    const tsc_js_abs = try std.fs.path.join(testing.allocator, &.{ cwd_abs, tsc_js_rel });
    defer testing.allocator.free(tsc_js_abs);

    // Phase 1: Run real TypeScript compiler with ALL strict flags!
    const tsc_res = try std.process.run(testing.allocator, testing.io, .{
        .cwd = .{ .dir = tmp.dir },
        .argv = &.{
            "node",
            tsc_js_abs,
            "--noEmit",
            "--strict",
            "--exactOptionalPropertyTypes",
            "--erasableSyntaxOnly",
            "--allowImportingTsExtensions",
            "--target",
            "es2022",
            "--module",
            "nodenext",
            "--moduleResolution",
            "nodenext",
            "bindings.gen.ts",
            "verify_client.ts",
        },
    });
    defer testing.allocator.free(tsc_res.stdout);
    defer testing.allocator.free(tsc_res.stderr);

    if (!tsc_res.term.success()) {
        std.debug.print("\n=== tsc FAILED ===\nstdout:\n{s}\nstderr:\n{s}\n--- bindings.gen.ts ---\n{s}\n", .{
            tsc_res.stdout,
            tsc_res.stderr,
            ShowcaseRpc.ts_bindings,
        });
        return error.TscTypecheckFailed;
    }

    // Phase 2: Execute `node verify_client.ts` live and serve every RPC call through our real Zig `Router`!
    var state = AppState{};
    var router = ShowcaseRpc.bind(.{ .app = &state });
    const handler = router.handler();

    var child = try std.process.spawn(testing.io, .{
        .cwd = .{ .dir = tmp.dir },
        .argv = &.{ "node", "verify_client.ts" },
        .stdin = .pipe,
        .stdout = .pipe,
        .stderr = .inherit,
    });
    defer child.kill(testing.io);

    var out_buf: [4096]u8 = undefined;
    var in_buf: [4096]u8 = undefined;
    var child_reader = child.stdout.?.reader(testing.io, &out_buf);
    var child_writer = child.stdin.?.writer(testing.io, &in_buf);

    const codec = @import("codec.zig");
    const ReqPacket = struct {
        command: []const u8,
        payload: []const u8,
    };

    var completed_cleanly = false;
    while (try child_reader.interface.takeDelimiter('\n')) |raw_line| {
        const line = std.mem.trimEnd(u8, raw_line, "\r");
        if (std.mem.eql(u8, line, "DONE")) {
            completed_cleanly = true;
            break;
        }

        const pkt = try codec.decode(ReqPacket, testing.allocator, line);
        defer pkt.deinit();

        var rpc_resp = handler.invoke(testing.allocator, testing.io, pkt.value.command, pkt.value.payload);
        defer rpc_resp.deinit();

        if (rpc_resp.status == .ok) {
            try child_writer.interface.print("{{\"ok\":true,\"data\":{s}}}\n", .{rpc_resp.body.slice()});
        } else {
            try child_writer.interface.print("{{\"ok\":false,\"error\":{s}}}\n", .{rpc_resp.body.slice()});
        }
        try child_writer.interface.flush();
    }

    if (child.stdin) |*in_pipe| {
        in_pipe.close(testing.io);
        child.stdin = null;
    }
    const term = try child.wait(testing.io);
    try testing.expect(term == .exited and term.exited == 0);
    try testing.expect(completed_cleanly);
    try testing.expectEqual(@as(i128, 9007199254741000), state.balance);
}
