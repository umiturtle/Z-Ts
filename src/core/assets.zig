//! Unified Web Asset Resolver, SPA Fallback & HTTP `Range` Engine (`src/core/assets.zig`).
//!
//! Serves static/embedded assets (`zts.embedFrontend`) and optional custom loader callbacks
//! with identical, standards-compliant HTTP semantics across all OS custom protocols AND the
//! `zts_bridge` localhost preview server:
//! - Path canonicalization & percent-decoding with strict `../` traversal rejection (`400`).
//! - Accurate MIME resolution via `mime.zig` (ES Modules, Wasm, SVG, fonts, video/audio).
//! - Client-side SPA routing fallback (`/users/42` -> `/index.html` `200 OK`), while keeping
//!   missing file-extension subresources (`/missing.js` -> `404 Not Found`) cleanly separate!
//! - Full RFC 9110 `Range: bytes=...` slicing (`206 Partial Content` / `416 Range Not Satisfiable`).
//! - Optional `<head>` HTML injection hook for `window.__TAURI_INTERNALS__` & `<meta>` CSP tags.

const std = @import("std");
const Allocator = std.mem.Allocator;
const testing = std.testing;

const csp = @import("csp.zig");
const html_escape = @import("html_escape.zig");
const http_range = @import("http_range.zig");
const mime = @import("mime.zig");
const OwnedBytes = @import("owned_bytes.zig").OwnedBytes;
const url = @import("url.zig");

/// Single compile-time or static asset entry (e.g. generated by `zts.embedFrontend`).
pub const StaticAsset = struct {
    /// Canonical leading-slash route path (e.g. `"/index.html"`, `"/assets/app.js"`).
    path: []const u8,
    bytes: []const u8,
    /// Optional explicit MIME override; auto-detected from `path`/`bytes` when `null`.
    mime_type: ?[]const u8 = null,
};

/// Pluggable backing loader for dynamic filesystem / dev-server asset resolution.
pub const FallbackLoader = struct {
    ctx: ?*anyopaque = null,
    loadFn: *const fn (ctx: ?*anyopaque, allocator: Allocator, canonical_path: []const u8) anyerror!?OwnedBytes,
};

/// HTTP-equivalent status codes returned by `Assets.resolve`.
pub const AssetStatus = enum(u16) {
    ok = 200,
    partial_content = 206,
    bad_request = 400,
    not_found = 404,
    range_not_satisfiable = 416,
    internal_error = 500,
};

/// Complete, ownership-safe resolved HTTP/custom-protocol response.
pub const AssetResponse = struct {
    status: AssetStatus,
    mime_type: []const u8,
    body: OwnedBytes,
    /// Total uncompressed representation size (populates `Content-Range` on `206` and `416`).
    total_len: u64 = 0,
    /// Present iff `status == .partial_content` (`206`).
    byte_range: ?http_range.ByteRange = null,
    /// `true` when `/users/42` fell back to `/index.html`.
    used_spa_fallback: bool = false,

    pub fn deinit(self: *AssetResponse) void {
        self.body.deinit();
    }

    /// Formats the `Content-Range` header into `buf` when `status` is `206` or `416`, else `null`.
    pub fn contentRangeHeader(self: AssetResponse, buf: *[64]u8) ?[]const u8 {
        return switch (self.status) {
            .partial_content => if (self.byte_range) |r| r.formatContentRange(buf, self.total_len) else null,
            .range_not_satisfiable => blk: {
                var small: [48]u8 = undefined;
                const s = http_range.formatUnsatisfiableContentRange(&small, self.total_len);
                @memcpy(buf[0..s.len], s);
                break :blk buf[0..s.len];
            },
            else => null,
        };
    }
};

pub const ResolveOptions = struct {
    /// Incoming `Range` request header value (e.g. `"bytes=0-65535"`), if present.
    range_header: ?[]const u8 = null,
    /// Enable client-side SPA fallback to `/index.html` for extensionless routes.
    spa_fallback: bool = true,
    /// Optional initialization snippet injected into `<head>` for HTML responses (`<meta>` CSP + bootstrap `<script>`).
    html_head_injection: ?[]const u8 = null,
};

/// Zero-overhead asset table & protocol engine.
pub const Assets = struct {
    entries: []const StaticAsset = &.{},
    fallback_loader: ?FallbackLoader = null,

    /// Resolves `raw_url_path` into a ready-to-serve `AssetResponse`.
    pub fn resolve(
        self: Assets,
        allocator: Allocator,
        raw_url_path: []const u8,
        options: ResolveOptions,
    ) Allocator.Error!AssetResponse {
        var norm_buf: [2048]u8 = undefined;
        const canonical = url.decodeAndNormalizeUrlPath(&norm_buf, raw_url_path) catch {
            return .{
                .status = .bad_request,
                .mime_type = "text/plain; charset=utf-8",
                .body = OwnedBytes.static("Bad Request: Invalid or disallowed path"),
            };
        };

        const lookup_path = if (std.mem.eql(u8, canonical, "/")) "/index.html" else canonical;

        var used_spa_fallback = false;
        var found = try self.lookupExact(allocator, lookup_path);

        // Directory index check (`/about` -> `/about/index.html`) before SPA fallback
        if (found == null and !std.mem.endsWith(u8, lookup_path, "/index.html")) {
            var idx_buf: [2064]u8 = undefined;
            if (lookup_path.len + "/index.html".len <= idx_buf.len) {
                @memcpy(idx_buf[0..lookup_path.len], lookup_path);
                @memcpy(idx_buf[lookup_path.len .. lookup_path.len + "/index.html".len], "/index.html");
                found = try self.lookupExact(allocator, idx_buf[0 .. lookup_path.len + "/index.html".len]);
            }
        }

        // SPA fallback: ONLY when route has no file extension (so missing `.js`/`.wasm`/`.png` return 404!)
        if (found == null and options.spa_fallback and !hasFileExtension(lookup_path)) {
            found = try self.lookupExact(allocator, "/index.html");
            if (found != null) used_spa_fallback = true;
        }

        var raw_asset = found orelse {
            return .{
                .status = .not_found,
                .mime_type = "text/plain; charset=utf-8",
                .body = OwnedBytes.static("Not Found"),
            };
        };
        errdefer raw_asset.bytes.deinit();

        // Optional `<head>` HTML injection (CSP meta tag + IPC initialization bootstrap script)
        if (options.html_head_injection) |snippet| {
            if (snippet.len > 0 and mime.isHtml(raw_asset.mime_type)) {
                const injected = try html_escape.injectIntoHead(allocator, raw_asset.bytes.slice(), snippet);
                raw_asset.bytes.deinit();
                raw_asset.bytes = OwnedBytes.fromOwnedSlice(allocator, injected);
            }
        }

        const full_slice = raw_asset.bytes.slice();
        const total_len: u64 = full_slice.len;

        // Evaluate RFC 9110 `Range` header if provided
        if (options.range_header) |range_hdr| {
            switch (http_range.evaluate(range_hdr, total_len)) {
                .ignore => {},
                .unsatisfiable => {
                    raw_asset.bytes.deinit();
                    return .{
                        .status = .range_not_satisfiable,
                        .mime_type = raw_asset.mime_type,
                        .body = OwnedBytes.empty,
                        .total_len = total_len,
                        .used_spa_fallback = used_spa_fallback,
                    };
                },
                .partial => |br| {
                    const sub = br.slice(full_slice);
                    // Zero-copy slice if static; otherwise compact owned slice so full asset can free immediately!
                    const part_body: OwnedBytes = if (raw_asset.bytes.release_fn == null)
                        OwnedBytes.static(sub)
                    else
                        try OwnedBytes.dupe(allocator, sub);
                    raw_asset.bytes.deinit();
                    return .{
                        .status = .partial_content,
                        .mime_type = raw_asset.mime_type,
                        .body = part_body,
                        .total_len = total_len,
                        .byte_range = br,
                        .used_spa_fallback = used_spa_fallback,
                    };
                },
            }
        }

        return .{
            .status = .ok,
            .mime_type = raw_asset.mime_type,
            .body = raw_asset.bytes,
            .total_len = total_len,
            .used_spa_fallback = used_spa_fallback,
        };
    }

    const RawLookup = struct {
        mime_type: []const u8,
        bytes: OwnedBytes,
    };

    fn lookupExact(self: Assets, allocator: Allocator, canonical_path: []const u8) Allocator.Error!?RawLookup {
        for (self.entries) |entry| {
            if (std.mem.eql(u8, entry.path, canonical_path)) {
                return .{
                    .mime_type = entry.mime_type orelse mime.detect(entry.path, entry.bytes),
                    .bytes = OwnedBytes.static(entry.bytes),
                };
            }
        }
        if (self.fallback_loader) |loader| {
            const loaded_opt = loader.loadFn(loader.ctx, allocator, canonical_path) catch |err| switch (err) {
                error.OutOfMemory => return error.OutOfMemory,
                else => return null,
            };
            if (loaded_opt) |owned| {
                return .{
                    .mime_type = mime.detect(canonical_path, owned.slice()),
                    .bytes = owned,
                };
            }
        }
        return null;
    }
};

fn hasFileExtension(path: []const u8) bool {
    const slash = std.mem.lastIndexOfScalar(u8, path, '/') orelse 0;
    const base = path[slash + 1 ..];
    const dot = std.mem.lastIndexOfScalar(u8, base, '.') orelse return false;
    return dot > 0 and dot + 1 < base.len;
}

