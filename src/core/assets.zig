test "Assets engine handles static routes, SPA fallback vs 404 assets, traversal defense, Range 206/416, and HTML head injection" {
    const table = [_]StaticAsset{
        .{ .path = "/index.html", .bytes = "<!doctype html><html><head><title>Z-Ts</title></head><body></body></html>" },
        .{ .path = "/assets/app.js", .bytes = "export const ok = true;\n" },
        .{ .path = "/media/clip.mp4", .bytes = "0123456789ABCDEF" },
    };
    const assets = Assets{ .entries = &table };

    // 1. Root `/` resolves to `/index.html` + injects `<head>` bootstrap script cleanly
    {
        var resp = try assets.resolve(testing.allocator, "/", .{
            .html_head_injection = "<script>window.__ZTS__=1;</script>",
        });
        defer resp.deinit();
        try testing.expectEqual(AssetStatus.ok, resp.status);
        try testing.expectEqualStrings(mime.HTML_UTF8, resp.mime_type);
        try testing.expect(!resp.used_spa_fallback);
        try testing.expect(std.mem.indexOf(u8, resp.body.slice(), "<head><script>window.__ZTS__=1;</script><title>") != null);
    }

    // 2. SPA client route `/users/42/profile?tab=keys` falls back to `/index.html` (0 heap allocations without injection!)
    {
        var resp = try assets.resolve(testing.failing_allocator, "/users/42/profile?tab=keys", .{});
        defer resp.deinit();
        try testing.expectEqual(AssetStatus.ok, resp.status);
        try testing.expect(resp.used_spa_fallback);
        try testing.expectEqualStrings(mime.HTML_UTF8, resp.mime_type);
    }

    // 3. Missing `.js` asset MUST return 404 (never return HTML for a script import!)
    {
        var resp = try assets.resolve(testing.failing_allocator, "/assets/missing-chunk.js", .{});
        defer resp.deinit();
        try testing.expectEqual(AssetStatus.not_found, resp.status);
    }

    // 4. Encoded path traversal `../../etc/passwd` returns 400 Bad Request
    {
        var resp = try assets.resolve(testing.failing_allocator, "/assets/%2e%2e/%2e%2e/etc/passwd", .{});
        defer resp.deinit();
        try testing.expectEqual(AssetStatus.bad_request, resp.status);
    }

    // 5. Zero-allocation `206 Partial Content` and `416 Range Not Satisfiable` on `/media/clip.mp4`
    {
        var cr_buf: [64]u8 = undefined;
        var resp = try assets.resolve(testing.failing_allocator, "/media/clip.mp4", .{
            .range_header = "bytes=4-9",
        });
        defer resp.deinit();
        try testing.expectEqual(AssetStatus.partial_content, resp.status);
        try testing.expectEqualStrings("video/mp4", resp.mime_type);
        try testing.expectEqualStrings("456789", resp.body.slice());
        try testing.expectEqualStrings("bytes 4-9/16", resp.contentRangeHeader(&cr_buf).?);

        var unsat = try assets.resolve(testing.failing_allocator, "/media/clip.mp4", .{
            .range_header = "bytes=50-60",
        });
        defer unsat.deinit();
        try testing.expectEqual(AssetStatus.range_not_satisfiable, unsat.status);
        try testing.expectEqualStrings("bytes */16", unsat.contentRangeHeader(&cr_buf).?);
    }

    // Ensure `csp` module compiles & stays linked when referenced by downstream packages
    _ = csp;
}

test "P0-4: Accept-Encoding negotiation, q-values and wildcard" {
    try testing.expect(acceptsGzip("gzip"));
    try testing.expect(acceptsGzip("gzip, deflate, br"));
    try testing.expect(acceptsGzip("GZIP; q=1.0"));
    try testing.expect(acceptsGzip("deflate, *;q=0.5"));
    try testing.expect(!acceptsGzip(""));
    try testing.expect(!acceptsGzip("deflate, br"));
    try testing.expect(!acceptsGzip("gzip;q=0"));
    try testing.expect(!acceptsGzip("gzip;q=0, *;q=1"));
    try testing.expect(!acceptsGzip("*;q=0, gzip;q=0.0"));
    try testing.expect(acceptsGzip("*;q=0, gzip;q=0.7"));
}

test "P0-4: gzip twins are served only when negotiated, never with Range or HTML injection" {
    const flate = std.compress.flate;
    const line = "export function hello(){return 'ziggurats '.repeat(64);}\n";
    const raw: []const u8 = line ++ line ++ line ++ line ++ line ++ line ++ line ++ line;
    var window: [flate.max_window_len]u8 = undefined;
    var buffer = try std.Io.Writer.Allocating.initCapacity(testing.allocator, 4096);
    errdefer buffer.deinit();
    var compress = try flate.Compress.init(&buffer.writer, &window, .gzip, .default);
    try compress.writer.writeAll(raw);
    try compress.finish();
    const gz = try buffer.toOwnedSlice();
    defer testing.allocator.free(gz);
    try testing.expect(gz.len < raw.len);
    try testing.expectEqual(@as(u8, 0x1f), gz[0]);
    try testing.expectEqual(@as(u8, 0x8b), gz[1]);

    const entries = [_]StaticAsset{.{ .path = "/app.js", .bytes = raw }};
    const twins = [_]?[]const u8{gz};
    const assets = Assets{ .entries = &entries, .gzip_entries = &twins };

    // 1. No Accept-Encoding -> raw bytes, but Vary is still emitted (two representations exist).
    {
        var r = try assets.resolve(testing.allocator, "/app.js", .{});
        defer r.deinit();
        try testing.expectEqual(AssetStatus.ok, r.status);
        try testing.expectEqualStrings(raw, r.body.slice());
        try testing.expect(r.content_encoding == null);
        try testing.expect(r.vary_accept_encoding);
    }
    // 2. gzip accepted -> twin + Content-Encoding; total_len stays the uncompressed length.
    {
        var r = try assets.resolve(testing.allocator, "/app.js", .{ .accept_encoding = "gzip, deflate" });
        defer r.deinit();
        try testing.expectEqualStrings(gz, r.body.slice());
        try testing.expectEqualStrings("gzip", r.content_encoding.?);
        try testing.expect(r.vary_accept_encoding);
        try testing.expectEqual(@as(u64, raw.len), r.total_len);
    }
    // 3. Explicit refusal -> raw bytes even though a twin exists.
    {
        var r = try assets.resolve(testing.allocator, "/app.js", .{ .accept_encoding = "gzip;q=0" });
        defer r.deinit();
        try testing.expectEqualStrings(raw, r.body.slice());
        try testing.expect(r.content_encoding == null);
    }
    // 4. Range always operates on the raw representation (RFC 9110: ranges are over the selected
    //    representation), so gzip is disabled and 206 still works.
    {
        var r = try assets.resolve(testing.allocator, "/app.js", .{
            .accept_encoding = "gzip",
            .range_header = "bytes=0-5",
        });
        defer r.deinit();
        try testing.expectEqual(AssetStatus.partial_content, r.status);
        try testing.expectEqualStrings("export", r.body.slice());
        try testing.expect(r.content_encoding == null);
        try testing.expect(r.vary_accept_encoding);
    }
    // 5. A twin larger than the original is treated as "no twin" (never inflate the response).
    {
        const big_twins = [_]?[]const u8{raw ++ "extra"};
        const wasteful = Assets{ .entries = &entries, .gzip_entries = &big_twins };
        var r = try wasteful.resolve(testing.allocator, "/app.js", .{ .accept_encoding = "gzip" });
        defer r.deinit();
        try testing.expectEqualStrings(raw, r.body.slice());
        try testing.expect(r.content_encoding == null);
        try testing.expect(!r.vary_accept_encoding);
    }
    // 6. Missing / null twin always serves raw bytes.
    {
        const no_twins = [_]?[]const u8{null};
        const plain = Assets{ .entries = &entries, .gzip_entries = &no_twins };
        var r = try plain.resolve(testing.allocator, "/app.js", .{ .accept_encoding = "gzip" });
        defer r.deinit();
        try testing.expectEqualStrings(raw, r.body.slice());
        try testing.expect(r.content_encoding == null);
        const shorter = Assets{ .entries = &entries };
        var r2 = try shorter.resolve(testing.allocator, "/app.js", .{ .accept_encoding = "gzip" });
        defer r2.deinit();
        try testing.expectEqualStrings(raw, r2.body.slice());
    }
}
