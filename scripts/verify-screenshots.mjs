#!/usr/bin/env node
// scripts/verify-screenshots.mjs — CI gate for `examples/gallery` PNGs (`M5-04`).
//
// The gallery only proves "a file was written"; this script proves the file is a real,
// non-blank render of the page:
//
//   1. PNG structure (IHDR dimensions == manifest, SHA-256 == manifest)
//   2. decoded pixels: unique colours, per-pixel luminance statistics
//   3. per-theme expectations (`light` → bright, `dark` → dark)
//   4. exact centre-pixel colour for pages that paint a colour from a native scheme response
//
// It has zero npm dependencies (Node's built-in `zlib` does the inflate) so it runs on every OS
// runner without touching `tests/tauri/node_modules`. On success it also writes a self-contained
// `index.html` contact sheet next to the PNGs for humans.
//
// Usage:
//   5. `font_ok` — the page's own `document.fonts.check()` for the bundled ZTS fonts. Every OS
//      must render with the *same* woff2 files, otherwise the cross-OS comparison is meaningless.
//   6. a layout fingerprint (`{"app":"layout", boxes:[…]}`) must be present: it is what
//      `scripts/compare-screenshots.mjs` diffs between Linux / macOS / Windows.
//
// Usage:
//   node scripts/verify-screenshots.mjs <dir> [--require-native] [--require-counts 17]

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { parsePng, unfilter, stats } from './lib/png.mjs';

function fail(msg) {
  console.error(`FAIL screenshots ${msg}`);
  process.exit(1);
}

function contactSheet(dir, manifest, loose) {
  const rows = manifest.patterns
    .map(
      (p) => `    <figure>
      <img src="${encodeURIComponent(p.file)}" alt="${p.name}" loading="lazy">
      <figcaption><b>${p.name}</b><br><span>${p.width}×${p.height} · ${(p.bytes / 1024).toFixed(0)} KiB · ${p.theme}</span></figcaption>
    </figure>`,
    )
    .join('\n');
  const looseRows = loose
    .map(
      (l) => `    <figure>
      <img src="${encodeURIComponent(l.file)}" alt="${l.file}" loading="lazy">
      <figcaption><b>${l.file}</b><br><span>${l.width}×${l.height} · ${(l.bytes / 1024).toFixed(0)} KiB · browser capture</span></figcaption>
    </figure>`,
    )
    .join('\n');
  const html = `<!doctype html>
<meta charset="utf-8">
<title>Z-Ts screenshots — ${manifest.host}</title>
<style>
  :root { color-scheme: dark; }
  body { margin:0; padding:28px; background:#0b1120; color:#e2e8f0;
         font:14px/1.6 -apple-system, "Hiragino Sans", "Noto Sans CJK JP", sans-serif; }
  h1 { font-size:20px; margin:0 0 4px; }
  p.meta { margin:0 0 24px; color:#94a3b8; font-size:12px; }
  .grid { display:grid; grid-template-columns:repeat(auto-fill, minmax(300px, 1fr)); gap:18px; }
  figure { margin:0; background:#111c33; border:1px solid #1e293b; border-radius:12px; overflow:hidden; }
  img { display:block; width:100%; height:auto; background:#fff; }
  figcaption { padding:10px 12px; font-size:12px; color:#94a3b8; }
  figcaption b { color:#e2e8f0; }
</style>
<h1>Z-Ts screenshot gallery</h1>
<p class="meta">host=${manifest.host} · os=${manifest.os} · ${manifest.patterns.length} patterns · generated by examples/gallery (M5-04)</p>
<div class="grid">
${rows}
${looseRows}
</div>
`;
  writeFileSync(path.join(dir, 'index.html'), html);
}

// ---------------------------------------------------------------------------

const args = process.argv.slice(2);
const requireNative = args.includes('--require-native');
const countsIdx = args.indexOf('--require-counts');
const requireCounts = countsIdx >= 0 ? Number(args[countsIdx + 1]) : 0;
// `--require-counts` eats the next token, so skip flag/value pairs before picking the directory
// (otherwise `verify-screenshots.mjs --require-native 17 <dir>` would treat `17` as the dir).
const VALUE_FLAGS = new Set(['--require-counts']);
const positional = [];
for (let i = 0; i < args.length; i++) {
  if (VALUE_FLAGS.has(args[i])) {
    i += 1;
    continue;
  }
  if (args[i].startsWith('--')) continue;
  positional.push(args[i]);
}
// Take the last positional: flags may legitimately be written before the directory
// (`--require-native 17 <dir>`), leaving a stray number that is not the directory.
const dir = positional[positional.length - 1];
if (!dir) fail('usage: verify-screenshots.mjs <dir> [--require-native] [--require-counts N]');

const manifestPath = path.join(dir, 'manifest.json');
if (!existsSync(manifestPath)) fail(`missing ${manifestPath}`);
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

if (!manifest.host) fail('manifest has no host');
if (requireNative && manifest.host === 'mock') {
  fail(`host=mock — the gallery ran without a native backend (display / WebView2 runtime missing)`);
}
if (requireCounts > 0 && manifest.patterns.length < requireCounts) {
  fail(`only ${manifest.patterns.length} pattern(s) in the manifest, expected at least ${requireCounts}`);
}

const parseCount = 0;
/** Compact one-line view of the layout fingerprint's font probe (for logs and failures). */
function probeSummary(entry) {
  if (!entry.layout) return 'layout=(none)';
  let layout;
  try {
    layout = JSON.parse(entry.layout);
  } catch (err) {
    return `layout=(unreadable: ${err.message})`;
  }
  const probe = layout.probe;
  if (!probe) return 'probe=(none)';
  const paint = probe.paint ? Object.entries(probe.paint).map(([k, v]) => `${k}:${v}`).join(',') : '?';
  const fetchInfo = entry.font_fetch ? entry.font_fetch : '(no fontfetch message)';
  return (
    `sans0=${probe.sans0} sans0b=${probe.sans0b} serif0=${probe.serif0} mono0=${probe.mono0} ` +
    `cjk=${probe.cjk} generic0=${probe.generic0} ch44=${probe.ch44} size=${probe.size} ` +
    `paint=[${paint}] faces="${probe.faces}" status=${probe.status} fontfetch=${fetchInfo}`
  );
}

let checked = 0;
const lines = [];

for (const entry of manifest.patterns) {
  const file = path.join(dir, entry.file);
  if (!existsSync(file)) fail(`${entry.name}: missing ${entry.file}`);
  const buf = readFileSync(file);

  const sha = createHash('sha256').update(buf).digest('hex');
  if (entry.sha256 && sha !== entry.sha256) {
    fail(`${entry.name}: sha256 ${sha} != manifest ${entry.sha256} (file changed after the manifest)`);
  }

  const parsed = parsePng(buf, entry.file);
  const { width, height } = parsed.ihdr;
  if (width !== entry.width || height !== entry.height) {
    fail(`${entry.name}: IHDR ${width}x${height} != manifest ${entry.width}x${entry.height}`);
  }
  // Hi-DPI captures are integer multiples of the CSS viewport (1x on Xvfb, 2x on Retina).
  const scale = width / entry.css_width;
  if (!Number.isInteger(scale) || scale < 1 || scale > 3) {
    fail(`${entry.name}: width ${width} is not an integer multiple of css width ${entry.css_width}`);
  }
  if (Math.round(height / entry.css_height) !== scale) {
    fail(`${entry.name}: non-uniform scale (${width}x${height} vs css ${entry.css_width}x${entry.css_height})`);
  }

  const decoded = unfilter(parsed);
  const s = stats(decoded, parsed);

  if (s.unique < 8) fail(`${entry.name}: only ${s.unique} unique colours — looks blank`);
  if (s.max - s.min < 8) fail(`${entry.name}: luminance range ${s.min.toFixed(1)}..${s.max.toFixed(1)} — flat image`);

  const isMock = manifest.host === 'mock';
  if (!isMock) {
    if (entry.theme === 'light' && s.mean < 165) {
      fail(`${entry.name}: theme=light but mean luminance ${s.mean.toFixed(1)} (< 165)`);
    }
    if (entry.theme === 'dark' && s.mean > 95) {
      fail(`${entry.name}: theme=dark but mean luminance ${s.mean.toFixed(1)} (> 95)`);
    }
  }

  if (!isMock && entry.expect_center_rgb) {
    const [er, eg, eb] = entry.expect_center_rgb;
    const [r, g, b] = s.center;
    const tol = 16;
    if (Math.abs(r - er) > tol || Math.abs(g - eg) > tol || Math.abs(b - eb) > tol) {
      fail(`${entry.name}: centre pixel rgb(${r},${g},${b}) != expected rgb(${er},${eg},${eb}) ±${tol}`);
    }
  }

  // Native runs must prove the bundled fonts loaded and the page measured itself: without both,
  // the 3-OS comparison has nothing to compare.
  if (!isMock) {
    if (entry.font_ok !== true) {
      // Print the whole probe: "font_ok=false" alone has cost several CI round trips because it
      // does not say *which* part failed (fetch / face state / paint diff).
      fail(`${entry.name}: bundled ZTS fonts are not the ones being painted (font_ok=false) ${probeSummary(entry)}`);
    }
    if (!entry.layout) fail(`${entry.name}: no layout fingerprint (page never measured itself)`);
    // The page fetches the woff2 itself: a WebKit custom-scheme/CORS refusal shows up here even
    // when `font_ok` still looks fine, so keep it as its own gate.
    if (entry.font_fetch) {
      let probe = null;
      try {
        probe = JSON.parse(entry.font_fetch);
      } catch (err) {
        fail(`${entry.name}: unreadable font_fetch probe (${err.message})`);
      }
      if (probe && probe.ok !== true) {
        const why = probe.err ?? `status ${probe.status} bytes ${probe.bytes}`;
        fail(`${entry.name}: the bundled font is not fetchable from the page (${why})`);
      }
    }
  }

  checked += 1;
  // Keep the font probe in the log for every native capture: when a later step disagrees about
  // layout, this is the evidence that says *why* (fallback face vs. the real woff2).
  if (!isMock) lines.push(`      font: ${probeSummary(entry)}`);
  lines.push(
    `  ${entry.name.padEnd(16)} ${String(width).padStart(5)}x${String(height).padEnd(5)} ` +
      `scale=${scale}x unique=${String(s.unique).padStart(5)} ` +
      `mean=${s.mean.toFixed(1).padStart(5)} ${(buf.length / 1024).toFixed(0).padStart(5)} KiB`,
  );
}

if (checked === 0) fail('manifest contains no patterns');

// Loose PNGs (e.g. headless-Chrome captures of the Live Preview / SSG builds) are checked for
// structure and non-blankness too — they have no manifest entry, so only generic rules apply.
const known = new Set(manifest.patterns.map((p) => p.file));
const loose = [];
for (const name of readdirSync(dir).sort()) {
  if (!name.toLowerCase().endsWith('.png') || known.has(name)) continue;
  const buf = readFileSync(path.join(dir, name));
  const parsed = parsePng(buf, name);
  const decoded = unfilter(parsed);
  const s = stats(decoded, parsed);
  if (parsed.ihdr.width < 64 || parsed.ihdr.height < 64) fail(`${name}: ${parsed.ihdr.width}x${parsed.ihdr.height} too small`);
  if (s.unique < 8) fail(`${name}: only ${s.unique} unique colours — looks blank`);
  if (s.max - s.min < 8) fail(`${name}: flat image (luminance ${s.min.toFixed(1)}..${s.max.toFixed(1)})`);
  loose.push({ file: name, width: parsed.ihdr.width, height: parsed.ihdr.height, bytes: buf.length });
  lines.push(
    `  ${name.padEnd(16)} ${String(parsed.ihdr.width).padStart(5)}x${String(parsed.ihdr.height).padEnd(5)} ` +
      `scale=? unique=${String(s.unique).padStart(5)} mean=${s.mean.toFixed(1).padStart(5)} ` +
      `${(buf.length / 1024).toFixed(0).padStart(5)} KiB (loose)`,
  );
}

contactSheet(dir, manifest, loose);

console.log(lines.join('\n'));
console.log(
  `OK screenshots host=${manifest.host} os=${manifest.os} patterns=${checked} loose=${loose.length} dir=${dir}`,
);
void parseCount;
